// ─── Workday (large enterprises, GCCs, big tech) ─────────────────────────────
// Verified live 2026-09-30: POST https://{tenant}.wd{N}.myworkdayjobs.com/wday/cxs/{tenant}/{site}/jobs
// -> { total, jobPostings: [{ title, externalPath, locationsText, postedOn }] }
// Workday's search is fuzzy ("product manager" matches ~every job at a big
// company), so the query adds "India" (which matches the location) and titles
// are filtered afterwards. slug: { tenant, wd, site }, plus host for tenants on
// the shared myworkdaysite.com domain (Wells Fargo: wd1.myworkdaysite.com).
async function fetchWorkday(company) {
  const { tenant, wd, site, host } = company.slug;
  const base = `https://${host || `${tenant}.wd${wd}.myworkdayjobs.com`}`;
  const publicBase = host ? `${base}/recruiting/${tenant}/${site}` : `${base}/${site}`;
  const jobs = [];
  let total = 0; // Workday only reports the total on the first page (later pages say 0)
  for (let offset = 0; offset < 200; offset += 20) {
    const res = await fetch(`${base}/wday/cxs/${tenant}/${site}/jobs`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
      body: JSON.stringify({ appliedFacets: {}, limit: 20, offset, searchText: 'product manager India' }),
      signal: AbortSignal.timeout(30000),
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const data = await res.json();
    const page = data.jobPostings || [];
    if (offset === 0) total = data.total ?? 0;
    jobs.push(...page);
    if (page.length < 20 || jobs.length >= total) break;
  }
  return jobs.map(j => ({
    id: `workday-${tenant}-${j.externalPath}`,
    title: j.title,
    company: company.name,
    location: j.locationsText || '',
    url: `${publicBase}${j.externalPath}`,
    source: `Workday (${company.name})`,
  }));
}

