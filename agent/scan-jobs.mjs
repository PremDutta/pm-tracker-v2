// Returns { pmJobs, boards }: the PM postings, plus every company board read
// successfully this run (all roles), which the hiring-signal checks use.
async function fetchCompanyATS() {
  const companies = await loadCompanies();
  if (companies.length === 0) return { pmJobs: [], boards: [] };
  const boards = [];

  const results = await mapLimited(companies, 8, async (company) => {
    const fetcher = ATS_FETCHERS[company.ats];
    if (!fetcher) {
      console.error(`${company.name}: unknown ats "${company.ats}" — must be one of ${Object.keys(ATS_FETCHERS).join(', ')}`);
      return [];
    }
    try {
      const jobs = (await fetcher(company)).filter(j => j.title);
      boards.push({ company: company.name, jobs, fromDirectory: !!company.fromDirectory });
      return jobs
        .filter(j => PM_TITLE_REGEX.test(j.title) && (!company.indiaOnly || INDIA_RE.test(j.location || '')))
        .map(j => (company.fromDirectory ? { ...j, baselineKey: `co:${company.name}` } : j));
    } catch (err) {
      console.error(`${company.name} (${company.ats}) fetch failed:`, err.cause?.code || err.message);
      return [];
    }
  });

  return { pmJobs: results.flat(), boards, directoryRead: boards.filter(b => b.fromDirectory).map(b => `co:${b.company}`) };
}

async function loadSeen() {
  try {
    const raw = await fs.readFile(SEEN_FILE, 'utf8');
    return { baselinedOrgs: [], ...JSON.parse(raw) };
  } catch {
    return { ids: [], firstRun: true, baselinedOrgs: [] };
  }
}

async function saveSeen(ids, baselinedOrgs) {
  // Keep the file bounded: the most recent 3000 ids (govt careers pages add a
  // few hundred notice ids on top of the job feeds).
  const trimmed = ids.slice(-3000);
  await fs.writeFile(SEEN_FILE, JSON.stringify({ ids: trimmed, firstRun: false, baselinedOrgs: [...baselinedOrgs].sort() }, null, 2));
}

// Open PM roles in India per company, for the app's Companies tab. A company
// whose board failed this run keeps its last-known roles for up to 7 days.
async function saveCompanyRoles(pmJobs, boards) {
  let previous = { roles: {}, lastRead: {} };
  try { previous = { ...previous, ...JSON.parse(await fs.readFile(COMPANY_ROLES_FILE, 'utf8')) }; } catch { /* first run */ }
  const today = new Date().toISOString().slice(0, 10);
  const weekAgo = new Date(Date.now() - 7 * 86_400_000).toISOString().slice(0, 10);
  const read = new Set(boards.map(b => b.company));
  const roles = {};
  for (const [company, list] of Object.entries(previous.roles)) {
    if (!read.has(company) && (previous.lastRead[company] || '') >= weekAgo) roles[company] = list.map(r => ({ ...r, level: r.level || roleLevel(r.title) }));
  }
  const firstSeen = new Map(Object.values(previous.roles).flat().map(r => [r.id, r.firstSeen]));
  for (const j of pmJobs.filter(j => INDIA_RE.test(j.location || ''))) {
    (roles[j.company] ||= []).push({ id: j.id, title: j.title, location: j.location, url: j.url, level: roleLevel(j.title), firstSeen: firstSeen.get(j.id) || today });
  }
  const lastRead = { ...previous.lastRead };
  for (const c of read) lastRead[c] = today;
  const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
  for (const list of Object.values(roles)) list.sort((a, b) => a.title.localeCompare(b.title));
  await fs.writeFile(COMPANY_ROLES_FILE, JSON.stringify({ scannedAt: new Date().toISOString(), roles: sorted(roles), lastRead: sorted(lastRead) }, null, 2) + '\n');
}

// Writes the current govt openings for the app. A source that failed this run
// keeps its last-known openings rather than vanishing from the app; firstSeen
// is carried over so the app can badge what's new. lastRead records, per org,
// the last day the scanner could read it, so the app can say which orgs are
// covered automatically and which (geo-blocked, JS-only) need a manual check.
async function saveGovtOpenings({ jobs, failed, readOk }) {
  let previous = { openings: [], lastRead: {} };
  try {
    previous = { ...previous, ...JSON.parse(await fs.readFile(GOVT_OPENINGS_FILE, 'utf8')) };
  } catch { /* first run */ }
  const firstSeenById = new Map(previous.openings.map(o => [o.id, o.firstSeen]));
  const today = new Date().toISOString().slice(0, 10);
  // Carry-over is for a flaky day, not forever: once an org hasn't been read
  // for 7 days its old openings drop out (the app then marks it "Check manually").
  const weekAgo = new Date(Date.now() - 7 * 86_400_000).toISOString().slice(0, 10);
  const kept = previous.openings.filter(o => failed.includes(o.org) && (previous.lastRead[o.org] || '') >= weekAgo);
  const openings = [...jobs.map(j => ({ ...j, firstSeen: firstSeenById.get(j.id) || today })), ...kept]
    .sort((a, b) => (b.firstSeen || '').localeCompare(a.firstSeen || '') || a.id.localeCompare(b.id));
  const lastRead = { ...previous.lastRead };
  for (const org of readOk) lastRead[org] = today;
  const sortedLastRead = Object.fromEntries(Object.entries(lastRead).sort(([a], [b]) => a.localeCompare(b)));
  await fs.writeFile(GOVT_OPENINGS_FILE, JSON.stringify({ openings, lastRead: sortedLastRead }, null, 2) + '\n');
  return jobs;
}

async function main() {
  const isPm = (title) => PM_TITLE_REGEX.test(title);
  const [adzuna, jsearch, atsResult, govtResult, vcResult, fundingSignals, ycResult] = await Promise.all([
    fetchAdzuna(), fetchJSearch(), fetchCompanyATS(), fetchGovtOpenings(), fetchVcBoards(isPm), fetchFundingSignals(), fetchYcJobs(isPm),
  ]);
  const yc = ycResult.jobs;
  if (ycResult.ok) await saveRoleSnapshot(YC_ROLES_FILE, yc);
  const vc = vcResult.jobs;
  const companyATS = atsResult.pmJobs;
  await saveCompanyRoles(companyATS, atsResult.boards);
  const govt = await saveGovtOpenings(govtResult);
  const today = new Date().toISOString().slice(0, 10);
  // Funding news is shown for every raise in the app, but only raises at companies in
  // companies.json make it into the phone alert.
  const watched = new Set((await loadCompanies()).map(c => c.name.toLowerCase()));
  const atsSignals = [...await updateAtsSignals(atsResult.boards, isPm, today), ...fundingSignals.map(s => ({ ...s, ...(watched.has(s.company.toLowerCase()) && { watched: true }) }))];
  const freshSignals = await saveSignals(atsSignals, today);
  if (atsSignals.length) console.log(`Hiring signals: ${atsSignals.length} (${atsSignals.filter(s => s.type !== 'funding').map(s => `${s.type} @ ${s.company}`).join(', ') || 'funding news only'})`);
  const allJobs = [...adzuna, ...jsearch, ...companyATS, ...govt, ...vc, ...yc];
  console.log(`Fetched ${adzuna.length} from Adzuna, ${jsearch.length} from JSearch, ${companyATS.length} from company ATS feeds, ${govt.length} from govt/PSU sources, ${vc.length} from VC portfolio boards, ${yc.length} from YC (${allJobs.length} total).`);

  // AI PM roles: an AI-flavoured title anywhere, or any PM role at an AI-native
  // company; India-based or remote-open-to-India only. Govt roles excluded.
  const aiCompanies = new Set((await loadCompanies()).filter(c => c.sector === 'ai').map(c => c.name.toLowerCase()));
  const aiRoles = [...companyATS, ...vc, ...yc, ...adzuna, ...jsearch]
    .filter(j => indiaEligibility(j.location || '') || /india/i.test(j.source || ''))
    .map(j => (isAiTitle(j.title) ? { ...j, aiMatch: 'title' } : aiCompanies.has((j.company || '').toLowerCase()) ? { ...j, aiMatch: 'company' } : null))
    .filter(Boolean);
  await saveRoleSnapshot(AI_ROLES_FILE, aiRoles);
  console.log(`AI PM roles (India / remote-India): ${aiRoles.length}`);

  const seen = await loadSeen();
  const seenSet = new Set(seen.ids);
  // The first successful read of a govt careers page is a baseline: it can
  // hold every notice currently up, so record those silently and only alert
  // on what appears after. Per org, so a page that was unreachable for
  // weeks doesn't flood the alert the day it comes back.
  // Only a real backlog (4+ matching notices on that first read) is held back;
  // with the notice filter this strict, one or two matches are worth an alert.
  const baselined = new Set(seen.baselinedOrgs);
  const noticeCount = (org) => govt.filter(j => j.org === org && j.id.startsWith('govt-notice-')).length;
  const vcCount = (key) => vc.filter(j => j.baselineKey === key).length;
  const baselineNow = new Set([
    ...govtResult.noticePagesRead.filter(org => !baselined.has(org) && noticeCount(org) > 3),
    ...vcResult.readOk.filter(key => !baselined.has(key) && vcCount(key) > 3),   // VC boards list dozens of PM roles on first read
    ...atsResult.directoryRead.filter(key => !baselined.has(key) && companyATS.filter(j => j.baselineKey === key).length > 3),
    ...(ycResult.ok && !baselined.has('yc') && yc.length > 3 ? ['yc'] : []),
  ]);
  const inBaseline = (j) => (j.id.startsWith('govt-notice-') && baselineNow.has(j.org)) || (j.baselineKey && baselineNow.has(j.baselineKey));
  const newJobs = allJobs.filter(j => j.id && !seenSet.has(j.id) && !inBaseline(j));
  if (baselineNow.size) console.log(`Sources with a backlog on first read (recorded, no alert): ${[...baselineNow].join(', ')}`);

  // Every new job goes into the digest queue and is marked seen: the queue,
  // not the seen list, is what holds it until a digest is delivered.
  let queue = await loadQueue();
  const todayIst = istToday();
  const digestSignals = freshSignals.filter(s => s.type !== 'funding' || s.watched);
  if (seen.firstRun) {
    console.log('First run — recording current jobs as a baseline, not sending an alert for all of them.');
  } else {
    console.log(newJobs.length ? `${newJobs.length} new job(s) since last run, queued for the morning digest.` : 'No new jobs since last run.');
    // Jobs left unseen by older runs that had no alert channel are picked up here too.
    queue = enqueue(queue, newJobs, digestSignals, todayIst);
  }

  // Urgent: can't wait for 8 AM.
  const openings = JSON.parse(await fs.readFile(GOVT_OPENINGS_FILE, 'utf8')).openings || [];
  const urgent = urgentItems({ newJobs: seen.firstRun ? [] : newJobs, openings, signals: freshSignals, reminders: queue.reminders, today: todayIst });
  const urgentMsg = urgentText(urgent, todayIst);
  if (urgentMsg) {
    console.log(`Urgent: ${urgent.newClosing.length} new govt role(s) closing soon, ${urgent.reminders.length} deadline reminder(s), ${urgent.reposted.length} reposted role(s).`);
    if (await sendAlert(urgentMsg)) queue = { ...queue, reminders: markReminders(queue.reminders, urgent.reminders, openings, todayIst) };
    else console.log('Urgent alert not delivered; reminders will retry next run.');
  }
  queue = { ...queue, reminders: markReminders(queue.reminders, [], openings, todayIst) };

  // Morning digest: the 8 AM IST run (or a manual run with send_digest) sets SEND_DIGEST=1.
  if (env('SEND_DIGEST') === '1') {
    const text = digestText(queue, openings, todayIst);
    if (!text) console.log('Digest: nothing new to send.');
    else if (await sendAlert(text)) {
      console.log(`Digest sent: ${queue.jobs.length} job(s), ${queue.signals.length} signal(s).`);
      queue = { ...queue, jobs: [], signals: [] };
    } else {
      console.log(`Digest not delivered; ${queue.jobs.length} job(s) stay queued for the next digest.`);
    }
  } else if (queue.jobs.length) {
    console.log(`Digest queue: ${queue.jobs.length} job(s), ${queue.signals.length} signal(s) waiting for 8:00 AM IST.`);
  }
  await saveQueue(queue);

  // Dedupe — without this, a job that's still listed on a later run (the
  // common case, since postings stay up for weeks) gets re-appended every
  // single run, silently filling the id cap with repeats of the same
  // handful of jobs instead of real history.
  // Every careers page read this run is baselined, including ones with no
  // matching notice yet, so the first real notice on it later does alert.
  await saveSeen([...new Set([...seen.ids, ...allJobs.map(j => j.id)])], new Set([...baselined, ...govtResult.noticePagesRead, ...vcResult.readOk, ...atsResult.directoryRead, ...(ycResult.ok ? ['yc'] : [])]));
}

// Keep the process alive until main() settles. The per-request timeouts
// (AbortSignal.timeout) use unref'd timers, so if every remaining request
// stalls, Node would otherwise exit 0 mid-run, silently, leaving the state files
// half-updated for the commit step. With the loop held open those timeouts
// fire and the stalled requests fail normally; the watchdog is the backstop.
const keepAlive = setInterval(() => {}, 60_000);
const watchdog = setTimeout(() => {
  console.error('Agent run exceeded 15 minutes; aborting without saving.');
  process.exit(1);
}, 15 * 60_000);

main()
  .catch(err => {
    console.error('Agent run failed:', err);
    process.exitCode = 1;
  })
  .finally(() => {
    clearInterval(keepAlive);
    clearTimeout(watchdog);
  });
