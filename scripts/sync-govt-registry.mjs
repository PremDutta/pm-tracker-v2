// Regenerates the two govt data files from the india-govt-search registry
// (the curl-verified orgs.json in the ai-job-search repo), so the app, the
// scanner, and that registry never drift apart:
//
//   src/data/govtOrgsList.js  - the app's Govt & PSU directory (high/medium PM relevance)
//   agent/govt-sources.json   - every org the scanner can read as structured JSON
//                               (json_api / embedded_json), plus JSON job boards
//
// Usage:
//   node scripts/sync-govt-registry.mjs [path/to/orgs.json]
// Default path: ~/ai-job-search/.agents/skills/india-govt-search/orgs.json

import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_REGISTRY = path.join(os.homedir(), 'ai-job-search/.agents/skills/india-govt-search/orgs.json');
const registryPath = process.argv[2] || DEFAULT_REGISTRY;

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const siteDomain = (url) => new URL(url).hostname.toLowerCase().replace(/^(www|careers|career|jobs|ora|recruitment|opportunities)\./, '');
const RELEVANCE_ORDER = { high: 0, medium: 1, low: 2 };

const registry = JSON.parse(await fs.readFile(registryPath, 'utf8'));
const byName = new Map(registry.orgs.map(o => [o.name, o]));

// ── App directory ───────────────────────────────────────────────────────────
const directory = registry.orgs
  .filter(o => o.pm_relevance === 'high' || o.pm_relevance === 'medium')
  .sort((a, b) => RELEVANCE_ORDER[a.pm_relevance] - RELEVANCE_ORDER[b.pm_relevance] || a.short.localeCompare(b.short, 'en', { sensitivity: 'base' }))
  .map(o => ({
    id: slug(o.short),
    short: o.short,
    name: o.name,
    category: o.category,
    relevance: o.pm_relevance,
    careersUrl: o.careers_url,
    domain: siteDomain(o.careers_url),
    ...(o.parent && { parent: o.parent }),
    ...(o.location && { location: o.location }),
    ...(o.covered_by && { listedOn: byName.get(o.covered_by)?.short || o.covered_by }),
    // Sites that reject every non-browser request: the weekly link check skips them.
    ...(o.fetch_method === 'blocked' && { blocksBots: true }),
  }));

const ids = new Set();
for (const o of directory) {
  if (ids.has(o.id)) throw new Error(`Duplicate org id "${o.id}" - make the registry "short" names unique`);
  ids.add(o.id);
}

const toJs = (obj) => '{' + Object.entries(obj).map(([k, v]) => `${k}:${JSON.stringify(v)}`).join(', ') + '}';
const listJs = `// GENERATED by scripts/sync-govt-registry.mjs from the india-govt-search
// registry (verified ${registry.verified}). Do not hand-edit: fix the registry
// and re-run the script. High/medium PM-relevance orgs only.
//
// relevance: 'high' = has hired for product roles directly; 'medium' = digital /
// tech-heavy org where PM-shaped roles appear under other titles.
// listedOn: no working page of its own; openings appear on that org's portal.
// blocksBots: site rejects automated requests (works in a browser).

export const GOVT_REGISTRY_VERIFIED = ${JSON.stringify(registry.verified)};

export const GOVT_ORGS = [
${directory.map(o => '  ' + toJs(o) + ',').join('\n')}
];
`;

// ── Scanner sources ─────────────────────────────────────────────────────────
const sources = registry.orgs
  .filter(o => (o.fetch_method === 'json_api' && o.api) || (o.fetch_method === 'embedded_json' && o.embedded))
  .map(o => ({
    name: o.name,
    short: o.short,
    category: o.category,
    relevance: o.pm_relevance,
    careersUrl: o.careers_url,
    ...(o.location && { location: o.location }),
    kind: o.fetch_method === 'json_api' ? 'api' : 'embedded',
    config: o.api || o.embedded,
  }));

for (const feed of registry.feeds || []) {
  if (feed.type !== 'json' || !feed.api) continue; // RSS feeds are broad sarkari aggregators: too noisy for PM alerts
  sources.push({
    name: feed.name,
    short: feed.name,
    category: 'job_board',
    relevance: 'high',
    careersUrl: new URL(feed.url).origin + '/',
    kind: 'api',
    config: { url: feed.url, ...feed.api },
  });
}

const sourcesJson = JSON.stringify({
  _comment: 'GENERATED by scripts/sync-govt-registry.mjs. Structured govt sources read by agent/govt.mjs; see the registry\'s SKILL.md for the field format.',
  verified: registry.verified,
  sources,
}, null, 2) + '\n';

await fs.writeFile(path.join(ROOT, 'src/data/govtOrgsList.js'), listJs);
await fs.writeFile(path.join(ROOT, 'agent/govt-sources.json'), sourcesJson);
console.log(`Wrote ${directory.length} orgs to src/data/govtOrgsList.js and ${sources.length} sources to agent/govt-sources.json (registry verified ${registry.verified}).`);
