// Builds the Companies-tab directory from scripts/company-directory.json (the
// curated, live-verified list of MNCs, IT majors, big tech and Indian unicorns):
//
//   src/data/companyDirectory.js      every company: careers page, ATS, group
//   agent/directory-companies.json    the ones with a job feed the scanner can
//                                     read, so their open PM roles in India
//                                     show up live in the tab and in alerts
//
// Usage: node scripts/build-company-directory.mjs

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// ATS readers the scanner has (agent/scan-jobs.mjs ATS_FETCHERS).
const SCANNABLE = new Set(['greenhouse', 'lever', 'ashby', 'smartrecruiters', 'workable', 'recruitee', 'zoho', 'keka', 'freshteam', 'workday', 'eightfold', 'oracle', 'successfactors', 'amazon']);

const src = JSON.parse(await fs.readFile(path.join(ROOT, 'scripts/company-directory.json'), 'utf8'));
const companies = src.companies;

const seen = new Set();
for (const c of companies) {
  const key = c.name.toLowerCase();
  if (seen.has(key)) throw new Error(`Duplicate company "${c.name}"`);
  seen.add(key);
  if (!c.careersUrl) throw new Error(`${c.name}: missing careersUrl`);
}

const scannable = companies.filter(c => c.readable && SCANNABLE.has(c.ats) && c.slug);
const app = companies
  .map(c => ({
    name: c.name,
    group: c.group,
    ...(c.sector && { sector: c.sector }),
    ...(c.status && { status: c.status }),
    careersUrl: c.careersUrl,
    ...(c.searchUrl && { searchUrl: c.searchUrl }),
    ats: c.ats || 'custom',
    scanned: scannable.includes(c),
    ...(c.note && { note: c.note }),
  }))
  .sort((a, b) => a.name.localeCompare(b.name, 'en', { sensitivity: 'base' }));

const toJs = (o) => '{' + Object.entries(o).map(([k, v]) => `${k}:${JSON.stringify(v)}`).join(', ') + '}';
await fs.writeFile(path.join(ROOT, 'src/data/companyDirectory.js'), `// GENERATED by scripts/build-company-directory.mjs from scripts/company-directory.json
// (verified ${src.verified}). Do not hand-edit: change the JSON and re-run the script.
// scanned: the background scanner reads this company's job feed every 6 hours.

export const COMPANY_DIRECTORY_VERIFIED = ${JSON.stringify(src.verified)};

export const COMPANY_DIRECTORY = [
${app.map(c => '  ' + toJs(c) + ',').join('\n')}
];
`);

await fs.writeFile(path.join(ROOT, 'agent/directory-companies.json'), JSON.stringify(
  scannable.map(c => ({ name: c.name, ats: c.ats, slug: c.slug })), null, 2) + '\n');

const byGroup = app.reduce((acc, c) => ({ ...acc, [c.group]: (acc[c.group] || 0) + 1 }), {});
console.log(`${app.length} companies (${Object.entries(byGroup).map(([g, n]) => `${g} ${n}`).join(', ')}); ${scannable.length} scanned.`);
